const Scene = require('node-vk-bot-api/lib/scene');
const Markup = require('node-vk-bot-api/lib/markup');
const { askAi } = require('../ai');

function menuKeyboard() {
  return Markup
    .keyboard([
      'Теория',
      'Тест',
      'Ситуации',
      'Задай вопрос',
    ])
    .oneTime();
}

const theoryPrompt = `
Ты — эксперт по технике пожарной безопасности и методист по обучению детей и взрослых.
Задача: Выдай теорию по теме «Техника пожарной безопасности» строго по шаблону, который я приведу ниже.
Требования к ответу:
1. Используй мой шаблон: каждый пункт начинается с названия правила и краткого объяснения (как в моём примере).
2. Количество правил: ровно 9 
3. Тон: чёткий, понятный, без воды, с примерами действий. Запрещено использовать * (звездочки).
4. Охвати такие подтемы: причины пожара, действия при обнаружении дыма/огня, эвакуация, использование огнетушителя, правила поведения в задымлённом помещении, вызов служб, ошибки при пожаре.
Пример (то, как должен выглядеть ответ):

Не играй с огнём:
…Теория… (2-3 предложения)
Знай пути эвакуации: 
…Теория… (2-3 предложения)
(дальше продолжай в таком же духе)

Подзаголовки возьми те, которые я тебе сейчас напишу: 1. Не играй с огнём; 2. Сухие руки — сухая безопасность; 3. Не перегружай сеть; 4. Повреждённый кабель = опасность; 5. Знай   пути эвакуации; 6. Дым? Пригнись и закрой лицо; 7. Не прячься, не возвращайся; 8. Остановись-упади-катись; 9. Вызов 101/112 
Теперь сгенерируй свои 9 правил по пожарной безопасности, используя этот стиль и структуру.
`;

const theoryScene = new Scene('theory',
  async (ctx) => {
    try {
      const answer = await askAi(theoryPrompt);

      ctx.scene.leave();
      ctx.reply(answer, null, menuKeyboard());
    } catch (error) {
      console.error(error);

      ctx.scene.leave();
      ctx.reply('Не получилось получить теорию от нейросети. Проверь AI_API_KEY и AI_BASE_URL в .env.', null, menuKeyboard());
    }
  });
module.exports = theoryScene;
