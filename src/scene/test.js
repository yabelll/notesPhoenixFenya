const buttonKeyboard = Markup.keyboard(['1', '2', '3', '4']).oneTime();

function resetTestScore(ctx) {
  ctx.session.testScore = 0;
}

function addTestPoint(ctx, isCorrect) {
  if (isCorrect) {
    ctx.session.testScore = (ctx.session.testScore || 0) + 1;
  }
}

function getRatingMessage(score) {
  if (score >= 4) {
    return `Твой результат: ${score} из 5.\nМолодец! Ты освоил тему.`;
  }

  return `Твой результат: ${score} из 5.\nСтоит повторно пройти материал и попробовать еще раз.`;
}

function addAiScoreRequirement(requirements) {
  return `${requirements}

В начале ответа обязательно напиши отдельной строкой:
SCORE:true
если ответ верный, или
SCORE:false
если ответ неверный.
После этой строки дай обычную краткую обратную связь.`;
}

function parseAiCheckedAnswer(answer) {
  const scoreMatch = answer.match(/^\s*SCORE:(true|false)\s*/i);

  if (!scoreMatch) {
    return {
      isCorrect: false,
      text: answer,
    };
  }

  return {
    isCorrect: scoreMatch[1].toLowerCase() === 'true',
    text: answer.slice(scoreMatch[0].length).trim(),
  };
}

async function askAiAndScore(ctx, userAnswer, requirements) {
  await ctx.reply('Феня думает...');
  const aiAnswer = await askAi(userAnswer, addAiScoreRequirement(requirements));
  const checkedAnswer = parseAiCheckedAnswer(aiAnswer);

  addTestPoint(ctx, checkedAnswer.isCorrect);

  return checkedAnswer.text;
}

